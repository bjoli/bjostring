// FastDouble: decimal text to a double by the Eisel-Lemire algorithm.
//
// .NET's double.Parse, and Utf8Parser.TryParse before it, first copy the
// digits into a buffer and then convert them. This reads the digits into one
// 64-bit integer and converts that with one or two 128-bit multiplications.
// On numbers of 15 to 17 digits, as in a JSON file of coordinates, it is about
// 2.4 times faster.
//
// It answers only what it is sure of, and is told so by its caller's result:
// text that is not -?digits[.digits][(e|E)[+-]digits], more than 19
// significant digits, an exponent out of the table's range, a result that is
// not a normal double, and the cases where the 128-bit product cannot decide
// the rounding all answer false. The caller then parses as before. So a
// number this answers is the double that double.Parse gives for it.
//
// The algorithm and the table are as in Go's strconv (eisel_lemire.go), by
// Nigel Tao, after Daniel Lemire, "Number Parsing at a Gigabyte per Second",
// Software: Practice and Experience 51(8), 2021. The table is the 128 bits of
// each power of ten from 1e-348 to 1e347, normalized so the top bit is set and
// rounded down.

using System.Numerics;
using System.Runtime.CompilerServices;

namespace BjoString;

[NonUserCode]
internal static class FastDouble
{
    private const int MinExp10 = -348;
    private const int MaxExp10 = 347;

    /// <summary>
    /// The double the UTF-8 text is, when the text is in the plain form and
    /// the conversion is certain. False otherwise, with nothing decided.
    /// </summary>
    public static bool TryParse(ReadOnlySpan<byte> s, out double value)
    {
        value = 0;
        int i = 0;
        int n = s.Length;
        bool neg = false;

        if (i < n && (s[i] == (byte)'-' || s[i] == (byte)'+'))
        {
            neg = s[i] == (byte)'-';
            i++;
        }

        ulong man = 0;
        int digits = 0;      // significant digits in man
        int dropped = 0;     // exponent adjustment from the decimal point
        bool any = false;

        // Integer part. Leading zeros are not significant.
        while (i < n && (uint)(s[i] - '0') <= 9)
        {
            uint d = (uint)(s[i] - '0');
            if (man != 0 || d != 0)
            {
                if (digits == 19) return false;
                man = man * 10 + d;
                digits++;
            }
            any = true;
            i++;
        }

        if (i < n && s[i] == (byte)'.')
        {
            i++;
            while (i < n && (uint)(s[i] - '0') <= 9)
            {
                uint d = (uint)(s[i] - '0');
                if (man != 0 || d != 0)
                {
                    if (digits == 19) return false;
                    man = man * 10 + d;
                    digits++;
                }
                dropped--;
                any = true;
                i++;
            }
        }

        if (!any) return false;

        int exp = 0;
        if (i < n && (s[i] == (byte)'e' || s[i] == (byte)'E'))
        {
            i++;
            bool expNeg = false;
            if (i < n && (s[i] == (byte)'-' || s[i] == (byte)'+'))
            {
                expNeg = s[i] == (byte)'-';
                i++;
            }
            if (i == n || (uint)(s[i] - '0') > 9) return false;
            while (i < n && (uint)(s[i] - '0') <= 9)
            {
                // Past 10000 the result is 0 or infinity whatever the digits,
                // and the table answers false for both.
                if (exp < 10000) exp = exp * 10 + (s[i] - '0');
                i++;
            }
            if (expNeg) exp = -exp;
        }

        if (i != n) return false;

        return EiselLemire(man, exp + dropped, neg, out value);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static bool EiselLemire(ulong man, int exp10, bool neg, out double f)
    {
        f = 0;
        if (man == 0)
        {
            f = neg ? -0.0 : 0.0;
            return true;
        }
        if (exp10 < MinExp10 || exp10 > MaxExp10) return false;

        // Normalization.
        int clz = BitOperations.LeadingZeroCount(man);
        man <<= clz;
        const int bias = 1023;
        ulong retExp2 = unchecked((ulong)(((217706 * exp10) >> 16) + 64 + bias) - (ulong)clz);

        // Multiplication.
        int at = (exp10 - MinExp10) * 2;
        ulong xHi = Math.BigMul(man, Table[at], out ulong xLo);

        // Wider approximation.
        if ((xHi & 0x1FF) == 0x1FF && xLo + man < man)
        {
            ulong yHi = Math.BigMul(man, Table[at + 1], out ulong yLo);
            ulong mergedHi = xHi;
            ulong mergedLo = xLo + yHi;
            if (mergedLo < xLo) mergedHi++;
            if ((mergedHi & 0x1FF) == 0x1FF && mergedLo + 1 == 0 && yLo + man < man) return false;
            xHi = mergedHi;
            xLo = mergedLo;
        }

        // Shifting to 54 bits.
        ulong msb = xHi >> 63;
        ulong retMantissa = xHi >> (int)(msb + 9);
        retExp2 -= 1 ^ msb;

        // Half-way ambiguity.
        if (xLo == 0 && (xHi & 0x1FF) == 0 && (retMantissa & 3) == 1) return false;

        // From 54 to 53 bits.
        retMantissa += retMantissa & 1;
        retMantissa >>= 1;
        if ((retMantissa >> 53) > 0)
        {
            retMantissa >>= 1;
            retExp2 += 1;
        }

        // Zero or underflow is subnormal, and 0x7FF or above is infinity: both
        // are left to the caller.
        if (retExp2 - 1 >= 0x7FF - 1) return false;

        ulong bits = (retExp2 << 52) | (retMantissa & 0x000FFFFFFFFFFFFF);
        if (neg) bits |= 0x8000000000000000;
        f = BitConverter.UInt64BitsToDouble(bits);
        return true;
    }

